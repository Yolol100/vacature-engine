"""Public-only specialist handoff: no CV or portfolio data in Action artifacts."""
import json
import unittest

from scripts.specialist_handoff import public_specialist_handoff


class SpecialistHandoffTests(unittest.TestCase):
    def test_only_public_role_identity_and_digest_allowlist_are_exported(self):
        candidate = {
            "official_role_candidate_url":
                "https://jobs.ashbyhq.com/employer/role?token=SECRET123#tracking",
            "title": "WordPress Developer", "employer": "Example",
            "still_to_verify": ["employer_required_work_languages",
                                "verified_core_duties_and_score_anchors",
                                "PRIVATE NAME: should never be exported"],
            "assessment_context": {
                "policy_sha256": "a" * 64,
                "candidate_evidence_sha256": "b" * 64,
                "observation_sha256": "c" * 64,
                "official_page_sha256": "d" * 64,
            },
            "technical_requirement_review": {"claim": "PRIVATE CV PROOF"},
            "candidate_evidence": ["PERSONAL LIBRARY FILE ID"],
            "source_locator": "PRIVATE SECTION",
            "assessment": {"years_of_experience": 10, "email": "private@example.org"},
        }
        output = public_specialist_handoff([candidate])
        self.assertEqual(output["schema"], "private-specialist-review-queue.v1")
        self.assertEqual(len(output["queue"]), 1)
        role = output["queue"][0]
        self.assertEqual(role["official_role_candidate_url"],
                         "https://jobs.ashbyhq.com/employer/role")
        self.assertTrue(role["ready_for_verified_assessment"])
        self.assertIsNone(role["autogenerated_score"])
        self.assertFalse(role["auto_application"])
        serialized = json.dumps(output)
        for private in ("SECRET123", "PRIVATE CV PROOF", "PERSONAL LIBRARY",
                        "PRIVATE SECTION", "private@example.org", "PRIVATE NAME"):
            self.assertNotIn(private, serialized)

    def test_unconfirmed_context_stays_pending_with_no_score(self):
        result = public_specialist_handoff([{
            "official_role_candidate_url": "https://jobs.ashbyhq.com/a/role",
            "assessment_context": {"policy_sha256": "invalid"},
            "still_to_verify": ["original_publication_date"],
        }])
        item = result["queue"][0]
        self.assertIsNone(item["assessment_context"])
        self.assertFalse(item["ready_for_verified_assessment"])
        self.assertIsNone(item["autogenerated_score"])

    def test_unsafe_or_authenticated_urls_are_excluded(self):
        for link in (
            "javascript:alert(1)", "https://username:secret@jobs.example.org/x",
            "http://127.0.0.1/role", "https://internal.local/job",
            "https://jobs.example.org:8443/role",
        ):
            with self.subTest(link=link):
                self.assertEqual(public_specialist_handoff([{
                    "official_role_candidate_url": link,
                }])["queue"], [])

    def test_digests_are_not_guessed_and_do_not_bypass_verified_gate(self):
        result = public_specialist_handoff([{
            "official_role_candidate_url": "https://jobs.example.org/role",
            "technical_requirement_review": {"mapped": True},
        }])
        self.assertEqual(result["queue"][0]["assessment_context"], None)
        self.assertTrue(result["requires_human_verification"])

    def test_empty_review_queue_is_valid_and_never_synthesizes_candidates(self):
        result = public_specialist_handoff([])
        self.assertEqual(result["queue"], [])
        self.assertTrue(result["no_personal_candidate_claims"])


if __name__ == "__main__":
    unittest.main()
