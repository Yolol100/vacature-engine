"""Privacy-minimized, public-only review worklist for the private specialist.

Never exports CandidateEvidence rows, claim text, evidence IDs, source locators,
private files or assessment receipts. Existing final_review.validate_assessment
continues to own the verified final-score gate on a trusted LOCAL runtime.
"""
from __future__ import annotations

import ipaddress
import re
from typing import Any
from urllib.parse import urlsplit, urlunsplit

_SHA = re.compile(r"[0-9a-f]{64}\Z")
_BLOCKER = re.compile(r"[a-z][a-z0-9_]{0,79}\Z")
_FIELDS = frozenset({
    "policy_sha256", "candidate_evidence_sha256",
    "observation_sha256", "official_page_sha256",
})


def _public_role_link(value: Any) -> str | None:
    if not isinstance(value, str) or len(value) > 2048:
        return None
    try:
        parts = urlsplit(value)
        if (parts.scheme != "https" or not parts.hostname or parts.username
                or parts.password or parts.port not in {None, 443}):
            return None
        host = parts.hostname.casefold()
        if (not host or "." not in host or host.endswith(
                (".local", ".internal", ".test", ".invalid", ".localhost"))):
            return None
        try:
            ipaddress.ip_address(host)
        except ValueError:
            pass
        else:
            return None
        # No marketing, tracking or signed query tokens in public handoff.
        return urlunsplit(("https", parts.netloc.lower(), parts.path, "", ""))
    except ValueError:
        return None


def public_specialist_handoff(
    review_candidates: list[dict[str, Any]], *,
    private_evidence_available: bool = True,
) -> dict[str, Any]:
    queue = []
    for candidate in review_candidates:
        if not isinstance(candidate, dict):
            continue
        link = _public_role_link(candidate.get("official_role_candidate_url"))
        if link is None:
            continue
        context = candidate.get("assessment_context")
        digests = (context if private_evidence_available and isinstance(context, dict) and
                   set(context) == _FIELDS and
                   all(isinstance(v, str) and _SHA.fullmatch(v)
                       for v in context.values()) else None)
        missing = candidate.get("still_to_verify")
        safe_missing = sorted({s for s in missing if isinstance(s, str)
                               and _BLOCKER.fullmatch(s)}) if isinstance(missing, list) else []
        item = {
            "official_role_candidate_url": link,
            "review_status": "private_specialist_required",
            "still_to_verify": safe_missing,
            "ready_for_verified_assessment": digests is not None,
            "assessment_context": dict(digests) if digests else None,
            "autogenerated_score": None,
            "auto_application": False,
        }
        queue.append(item)
    return {
        "schema": "private-specialist-review-queue.v1",
        "read_only": True,
        "requires_human_verification": True,
        "no_personal_candidate_claims": True,
        "private_candidate_evidence_loaded": private_evidence_available,
        "privacy_boundary": "github_public_role_and_digests_only",
        "queue": queue,
    }
